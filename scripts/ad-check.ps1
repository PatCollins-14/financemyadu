# Counts characters for ads/ad-copy.csv and flags anything outside the reported (UNVERIFIED) ranges
# or containing a banned phrase. Ranges: titles 16-24, descriptions 32-48. Verify in OpenAI's ad manager before use.
. "$PSScriptRoot\lib.ps1"
$root = Get-Root
$banned = Read-Json (Join-Path $root 'config\banned-phrases.json')
$csv = Import-Csv (Join-Path $root 'ads\ad-copy.csv')
$range = @{ title = @(16, 24); description = @(32, 48) }
$extra = @('fastest', 'guaranteed', 'preapproved', 'pre-approved', 'free', 'no obligation', 'lowest', 'rates as low')
$rows = @(); $bad = 0
foreach ($r in $csv) {
  $len = $r.text.Length
  $lo = $range[$r.type][0]; $hi = $range[$r.type][1]
  $flags = @()
  if ($len -lt $lo -or $len -gt $hi) { $flags += "length outside $lo-$hi" }
  foreach ($b in $banned.patterns) { if ($r.text -match [string]$b.re) { $flags += "banned: $($b.id)" } }
  foreach ($e in $extra) { if ($r.text -match [regex]::Escape($e)) { $flags += "avoid: $e" } }
  $status = $(if ($flags.Count) { $bad++; 'FLAG: ' + ($flags -join '; ') } else { 'ok' })
  $rows += [pscustomobject]@{ id = $r.id; type = $r.type; chars = $len; text = $r.text; status = $status }
}
$rows | Format-Table -AutoSize -Wrap | Out-String -Width 200 | Write-Host
$md = "| ID | Type | Characters | Text | Check |`n|---|---|---|---|---|`n"
foreach ($r in $rows) { $md += "| $($r.id) | $($r.type) | $($r.chars) | $($r.text) | $($r.status) |`n" }
Write-Text (Join-Path $root 'ads\ad-copy-counts.md') ("# Ad copy character counts`n`nGenerated by ``run.cmd adcheck``. Ranges (titles 16-24, descriptions 32-48) are UNVERIFIED; confirm in OpenAI's ad manager.`n`n" + $md)
Write-Host "$($rows.Count) variants checked, $bad flagged."
if ($bad) { exit 1 }
